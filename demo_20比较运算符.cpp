#include<iostream>
using namespace std;

int main()
{
    //比较运算符        //1为真，0为假
    //  ==
    int a=10;
    int b=20;

    cout<<(a==b)<<endl;
    cout<<(a!=b)<<endl;

    //  !=

    cout<<(a!=b)<<endl;

    //  >
    cout<<(a>b)<<endl;

    //  <
    cout<<(a<b)<<endl;

    //  >=
    cout<<(a>=b)<<endl;

    //  <=
    cout<<(a<=b)<<endl;





    return 0;
}